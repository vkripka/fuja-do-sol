export const STRINGS: Record<Lang, Strings> = { pt, en };

/** Rótulo de data curto (dia da semana, dia e mês) no idioma pedido. */
export function dateParts(key: string, lang: Lang): { weekday: string; day: string; month: string } {
  const [year, month, day] = key.split('-').map(Number);
  const wd = new Date(Date.UTC(year, month - 1, day)).getUTCDay();
  const s = STRINGS[lang];
  return { weekday: s.weekdays[wd], day: String(day), month: s.months[month - 1] };
}
